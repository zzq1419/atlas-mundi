# -*- coding: utf-8 -*-
"""修复题库里被压平的表格材料。

2025 那批真题是从网页/PDF 抓的，表格被拆成一格一行：
   降雨序
   号
   时段雨量
   ...
   1
   60
   48
页面用 pre-wrap 渲染，于是一张 3×8 的表竖着铺了半屏。

这里把识别得出的几张表重写成 [[table]] 标记（前端会画成真表格），
顺手清掉抓取时混进材料里的上一题残留。按材料原文匹配，跑几次结果一样。
"""
import io
import json

BANK = 'assets/bank/real.json'

# ---------------------------------------------------------------- 1) 河南卷 11—13：降雨过程数据表
HN_OLD_HEAD = '为探究降雨过程、土壤含水量与洪峰流量的关系'
HN_NEW = (
    '为探究降雨过程、土壤含水量与洪峰流量的关系，某科研小组在小流域模拟了形成相同洪峰流量的'
    '降雨过程，表为 3 次降雨过程数据（雨量单位：mm）。3 次降雨前土壤含水量相同且偏低。'
    '据此完成下面小题。\n'
    '[[table]]\n'
    '降雨序号|第 1 小时|第 2 小时|第 3 小时|第 4 小时|第 5 小时|第 6 小时|降雨总量\n'
    '1|60|48|32|10|8|7|165\n'
    '2|10|20|42|55|17|6|150\n'
    '3|10|19|23|32|42|17|143\n'
    '[[/table]]'
)

# ---------------------------------------------------------------- 2) 安徽卷 6—8：老城南四种更新方式
AH_OLD_HEAD = '老城南地区位于南京市内城南部'
AH_NEW = (
    '老城南地区位于南京市内城南部，经过持续更新改造，已成为城市新名片。'
    '下图示意老城南地区历史要素的空间分布，下表为老城南地区四种更新方式及案例。据此完成下面小题。\n'
    '[[table]]\n'
    '更新方式|案例\n'
    '复建仿古建筑群，历史文化空间的繁体仿真|夫子庙\n'
    '复原传统民居，发展时尚餐饮、文博展览、文旅节庆等产业|老门东\n'
    '改造工业遗址，创新多元化的文创业态|门西文化生态创意园\n'
    '利用闲置名人故居、游园绿地等创建公共阅读休憩空间|“转角·遇见”系列空间\n'
    '[[/table]]'
)

# ---------------------------------------------------------------- 3) 甘肃卷 15—16：输电线舞动天气状况
GS_OLD_HEAD = '输电线舞动是指架空输电线'
GS_NEW = (
    '输电线舞动是指架空输电线在覆冰及稳定风场的作用下产生的一种振动现象。'
    '该现象一般发生在近地面大幅降温和降雨天气过程中。下表为 2008 年 1 月 13～14 日'
    '我国某地输电线舞动发生时段的近地面及高空 3 千米天气状况。据此完成下面小题。\n'
    '[[table]]\n'
    '高度|降水形态|风向|舞动之前 48 小时内降温/℃\n'
    '近地面|液态|偏北风|15～18\n'
    '高空 3 千米|液态|西南风|2～3\n'
    '[[/table]]'
)

# ---------------------------------------------------------------- 4) 江西卷 11—13：材料前面混进了上一题
JX_OLD_HEAD = '9. M 集团将开采环节分散在全球多个国家'
JX_KEEP = '下图示意某年 11 月 10 日 0 时、9 时和 18 时的北美洲局部区域海平面气压和锋面位置。据此完成下列问题。'


def fix(items):
    n = {'hn': 0, 'ah': 0, 'gs': 0, 'jx': 0, 'stray': 0}
    for it in items:
        m = it.get('material') or ''
        if not m:
            continue

        if m.startswith(HN_OLD_HEAD):
            it['material'] = HN_NEW
            n['hn'] += 1
        elif m.startswith(AH_OLD_HEAD):
            it['material'] = AH_NEW
            n['ah'] += 1
        elif m.startswith(GS_OLD_HEAD):
            it['material'] = GS_NEW
            n['gs'] += 1
        elif m.startswith(JX_OLD_HEAD):
            it['material'] = JX_KEEP
            n['jx'] += 1
        else:
            # 首行是个两三字的残片（上一题的尾巴），去掉
            lines = m.split('\n')
            while lines and len(lines[0].strip()) <= 3 and lines[0].strip() not in ('',):
                lines.pop(0)
            if len(lines) != len(m.split('\n')):
                it['material'] = '\n'.join(lines).lstrip('\n')
                n['stray'] += 1
    return n


def main():
    d = json.load(io.open(BANK, encoding='utf-8'))
    n = fix(d['items'])
    d['ver'] = '2026-11-27-real-5'
    d['note'] = '高考地理真题（2024—2025）：选择题 + 材料分析题，材料图取自原卷 PDF；表格材料用 [[table]] 标记存真表格。'
    io.open(BANK, 'w', encoding='utf-8', newline='').write(
        json.dumps(d, ensure_ascii=False, separators=(',', ':')))
    print('河南 %d · 安徽 %d · 甘肃 %d · 江西 %d · 残片 %d' %
          (n['hn'], n['ah'], n['gs'], n['jx'], n['stray']))


if __name__ == '__main__':
    main()
