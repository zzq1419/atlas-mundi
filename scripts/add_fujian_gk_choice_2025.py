def prep_figs():
    """返回 {组起始题号: (路径, 宽, 高)}"""
    out = {}

    def save(im, name):
        if im.width > 1200:
            im = im.resize((1200, round(im.height * 1200 / im.width)), Image.LANCZOS)
        p = os.path.join(FIG, name)
        im.save(p, 'WEBP', quality=88, method=6)
        return p, im.size

    for grp in GROUPS:
        no, fig = grp[0], grp[2]
        if not fig:
            continue
        if fig == 'g32_35':
            a = Image.open(os.path.join(SRC, 'g32.png')).convert('RGB')
            b = Image.open(os.path.join(SRC, 'g35.png')).convert('RGB')
            w = max(a.width, b.width)
            gap = 40
            cv = Image.new('RGB', (w, a.height + gap + b.height), 'white')
            cv.paste(a, ((w - a.width) // 2, 0))
            cv.paste(b, ((w - b.width) // 2, a.height + gap))
            out[no] = save(cv, 'gk1005-%d.webp' % no)
        else:
            im = Image.open(os.path.join(SRC, fig + '.png')).convert('RGB')
            out[no] = save(im, 'gk1005-%d.webp' % no)
    return out


def main():
    figs = prep_figs()
    items = []
    for no, mat, fig, figalt, theme, subs in GROUPS:
        for k, (q, opts, ans, exp, diff) in enumerate(subs):
            n = no + k
            it = {
                'id': 'gk1005-2025-%d' % n,
                'type': 'choice', 'lv': 'sr', 'grade': '高中', 'band': '高中',
                'exam': EXAM, 'year': YEAR, 'paper': PAPER, 'no': n,
                'prov': PROV, 'city': CITY,
                'theme': theme, 'cat': '真题',
                'tags': ['真题', '2025', '福建卷', theme],
                'diff': diff, 'score': diff, 'point': 3,
                'material': mat, 'q': q, 'opts': opts, 'ans': ans,
                'ansText': '', 'exp': exp,
                'card': '', 'cardName': '',
                'src': '2025 年福建卷 · 第 %d 题' % n,
                'figure': '', 'figureAlt': '', 'figW': 0, 'figH': 0,
            }
            if fig and no in figs:
                p, (w, h) = figs[no]
                it['figure'] = p.replace(os.sep, '/')
                it['figureAlt'] = figalt
                it['figW'], it['figH'] = w, h
            items.append(it)

    d = json.load(io.open(BANK, encoding='utf-8'))
    byid = {i['id']: i for i in d['items']}
    add = [i for i in items if i['id'] not in byid]
    for i in items:
        if i['id'] in byid:
            byid[i['id']].update(i)
    d['items'].extend(add)
    d['ver'] = '2026-11-28-real-22'
    io.open(BANK, 'w', encoding='utf-8', newline='').write(
        json.dumps(d, ensure_ascii=False, separators=(',', ':')))
    print('福建卷选择题新增 %d 题，题库 %d 条' % (len(add), len(d['items'])))


if __name__ == '__main__':
    main()
