def to_webp(src, dst, maxw=1100):
    im = Image.open(src).convert('RGB')
    if im.width > maxw:
        im = im.resize((maxw, round(im.height * maxw / im.width)), Image.LANCZOS)
    im.save(dst, 'WEBP', quality=85, method=6)
    return im.size


def main():
    size = {}
    for no, src in ((26, 'q7_1'), (27, 'q7_3'), (28, 'q8_1')):
        p = os.path.join(FIG, 'zj2025-%d.webp' % no)
