def to_webp(src, dst, maxw=1100):
    im = Image.open(src).convert('RGB')
    if im.width > maxw:
        im = im.resize((maxw, round(im.height * maxw / im.width)), Image.LANCZOS)
    im.save(dst, 'WEBP', quality=85, method=6)
    return im.size


def main():
    size = {}
    for name, src in (('17', 'p4_2'), ('18', 'p5_1'), ('19', 'p5_2')):
        p = os.path.join(FIG, 'heb2025-%s.webp' % name)
        size[name] = to_webp(os.path.join(SRC, src + '.png'), p)

    items = []
    for no, mat, fig, figalt, subs, theme in MATERIAL:
        for k, (q, ans, exp, score) in enumerate(subs, 1):
            it = {
                'id': 'heb2025-%d-%d' % (no, k),
                'type': 'material', 'lv': 'sr', 'grade': '高三', 'band': '高中',
                'exam': EXAM, 'year': YEAR, 'paper': PAPER, 'no': '%d-%d' % (no, k),
                'prov': PROV, 'city': CITY,
                'theme': theme, 'cat': '真题',
                'tags': ['真题', '2025', '河北卷', theme],
                'diff': 6.2, 'score': score,
                'material': mat, 'q': q, 'ansText': ans, 'exp': exp,
                'opts': [], 'ans': -1,
                'src': '2025 河北卷 · 第 %d 题' % no,
                'figure': os.path.join(FIG, fig).replace(os.sep, '/'),
                'figureAlt': figalt,
                'figW': size[str(no)][0], 'figH': size[str(no)][1],
            }
            items.append(it)

    d = json.load(io.open(BANK, encoding='utf-8'))
    byid = {i['id']: i for i in d['items']}
    add = [i for i in items if i['id'] not in byid]
    for i in items:
        if i['id'] in byid:
            byid[i['id']].update(i)
    d['items'].extend(add)
    d['ver'] = '2026-11-28-real-11'
    io.open(BANK, 'w', encoding='utf-8', newline='').write(
        json.dumps(d, ensure_ascii=False, separators=(',', ':')))
    print('河北卷新增 %d 小问，题库 %d 条' % (len(add), len(d['items'])))


if __name__ == '__main__':
    main()
