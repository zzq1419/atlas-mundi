def main():
    bank = json.load(io.open(BANK, encoding='utf-8'))
    items = bank.get('items') or []
    have = {i['id'] for i in items}
    add = [x for x in R if x['id'] not in have]
    items.extend(add)
    bank['items'] = items
    nreal = sum(1 for i in items if i.get('cat') == '真题')
    bank['ver'] = '2026-11-25-real-3'
    io.open(BANK, 'w', encoding='utf-8', newline='').write(
        json.dumps(bank, ensure_ascii=False, separators=(',', ':')))
    print('新增真题 %d 条，题库 %d 题（其中真题 %d）' % (len(add), len(items), nreal))


main()
