R = []


def q(key, year, paper, no, theme, tags, diff, figure, material, subs, src=None):
    """一组材料题：material 共享，subs 是 [(小问, 答案, 解析, 分值)]"""
    for i, (text, ans, exp, score) in enumerate(subs, 1):
        R.append({
            'id': 'gk-%s-%s' % (key, i),
            'type': 'short',
            'lv': 'sr',
            'grade': '高三',
            'band': '高中',
            'theme': theme,
            'cat': '真题',
            'tags': tags,
            'diff': diff,
            'material': material,
            'figure': figure,
            'figureAlt': '%s %s 第 %s 题材料图' % (year, paper, no),
            'q': text,
            'ansText': ans,
            'exp': exp,
            'src': src or ('%s %s · 第 %s 题' % (year, paper, no)),
            'score': score,
            'year': str(year),
            'paper': paper,
            'no': str(no),
        })


